/// FT8/FT4 protocol constants and LDPC parity check matrix.
/// LDPC matrix _NM from ft8_encoder.py (verified against WSJT-X).

pub struct Params {
    pub sample_rate:     u32,
    /// Okres symbolu [s] — deskryptor protokolu, zachowany pod port AP/subtraction.
    #[allow(dead_code)]
    pub symbol_period:   f64,
    pub tone_spacing:    f64,
    pub samples_per_sym: usize,
    pub n_tones:         usize,
    pub n_sym:           usize,
    /// Okres slotu [s] — deskryptor protokolu (FT8=15, FT4=7.5), zachowany.
    #[allow(dead_code)]
    pub slot_period:     f64,
    /// Liczba tonow Costas — deskryptor protokolu (FT8=7, FT4=4), zachowany.
    #[allow(dead_code)]
    pub n_costas:        usize,
    pub costas_pos:      &'static [usize],
}

