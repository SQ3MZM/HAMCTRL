/// OSD (Ordered Statistics Decoding) — fallback for LDPC belief-propagation
/// (BP) decode failures. WSJT-X runs this when BP doesn't converge,
/// recovering some marginal/weak decodes BP alone misses.
///
/// v1 scope: searches only within the code's fixed systematic bits[0..91]
/// split, not full generic-position OSD with column permutation. Textbook
/// OSD permutes columns to find a non-singular 91-bit information set,
/// since an arbitrary "most reliable 91 of 174" selection might be
/// singular under the parity-check matrix. HAMCTRL's fixed [0..91] split
/// is the code's own systematic split and is never singular by
/// construction (GEN_PARITY maps ANY 91-bit word to a valid codeword), so
/// that machinery is unnecessary here. Trade-off: this searches bit-flip
/// patterns within the 91 systematic bits, not the genuinely most-reliable
/// 91 of all 174 — weaker than textbook OSD, simpler and correct. Can be
/// upgraded to full generic-position OSD later if live testing shows a gap.
///
/// IMPORTANT: candidates are validated by CRC-14 (check_crc on bits[0..91]),
/// NOT LDPC parity. Re-encoding ANY 91-bit systematic word through
/// GEN_PARITY always produces a codeword that trivially satisfies the
/// LDPC parity check by construction (that's what a systematic generator
/// matrix IS - it's defined to make every message word map to a valid
/// codeword) - so parity can never distinguish a correct 91-bit guess from
/// a wrong one here. CRC-14 (part of those same 91 bits) is the real
/// filter, exactly like the normal (non-OSD) decode path already relies
/// on downstream of BP.
use super::crc14::check_crc;
#[cfg(test)]
use super::crc14::crc14;

