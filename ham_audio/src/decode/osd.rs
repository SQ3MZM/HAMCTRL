/// Re-encode 91 systematic bits (data77+crc14) to the full 174-bit
/// codeword. Mirrors ft8_encoder.py::_ldpc_encode.
pub fn ldpc_encode_systematic(bits91: &[u8; 91]) -> [u8; 174] {
    let mut out = [0u8; 174];
    out[..91].copy_from_slice(bits91);
    for i in 0..83 {
        let mut parity = 0u8;
        for j in 0..91 {
            if GEN_PARITY[i][j] == 1 {
                parity ^= bits91[j];
            }
        }
        out[91 + i] = parity;
    }
    out
}

/// Pelny OSD (ordered statistics decoding) w ogolnej pozycji, uzywany gdy BP
/// nie zbiegl na zadnym zestawie LLR. W odroznieniu od try_osd (odwraca
/// pojedyncze bity tylko w stalych 91 bitach systematycznych) tutaj baza
/// informacyjna to 91 NAJPEWNIEJSZYCH niezaleznych pozycji z calych 174
/// (eliminacja Gaussa na kolumnach macierzy generujacej posortowanych wg
/// |LLR|), a przeszukiwanie obejmuje rzad 0, caly rzad 1 i rzad 2 na
/// `order2_width` najmniej pewnych bitach bazy. Wybierane jest slowo kodowe
/// o najmniejszej wazonej odleglosci od odebranego sygnalu; na koniec CRC.
/// Zwraca (slowo kodowe w oryginalnej kolejnosci bitow, odleglosc wazona).
pub fn osd_full(llr174: &[f32; 174], order2_width: usize) -> Option<([u8; 174], f32)> {
    type Row = [u64; 3];
    let get = |r: &Row, c: usize| (r[c >> 6] >> (c & 63)) & 1 == 1;
    let set = |r: &mut Row, c: usize| r[c >> 6] |= 1u64 << (c & 63);

    // Kolejnosc kolumn: od najpewniejszej.
    let mut perm: [usize; 174] = std::array::from_fn(|i| i);
    perm.sort_by(|&a, &b| llr174[b].abs().partial_cmp(&llr174[a].abs()).unwrap_or(std::cmp::Ordering::Equal));

    // Wiersze macierzy generujacej [I | P] w permutowanej kolejnosci kolumn.
    let mut inv = [0usize; 174];
    for (c, &orig) in perm.iter().enumerate() { inv[orig] = c; }
    let mut rows: Vec<Row> = (0..91).map(|r| {
        let mut row: Row = [0; 3];
        set(&mut row, inv[r]);
        for j in 0..83 {
            if GEN_PARITY[j][r] == 1 { set(&mut row, inv[91 + j]); }
        }
        row
    }).collect();

    // Eliminacja Gaussa: pivoty na kolejnych (najpewniejszych) kolumnach.
    let mut pivot_col = [0usize; 91];
    let mut k = 0usize;
    for c in 0..174 {
        if k == 91 { break; }
        let Some(r) = (k..91).find(|&r| get(&rows[r], c)) else { continue };
        rows.swap(r, k);
        let pr = rows[k];
        for rr in 0..91 {
            if rr != k && get(&rows[rr], c) {
                for w in 0..3 { rows[rr][w] ^= pr[w]; }
            }
        }
        pivot_col[k] = c;
        k += 1;
    }
    if k < 91 { return None; }

    let mut hd: Row = [0; 3];
    let mut absl = [0f32; 174];
    for c in 0..174 {
        let l = llr174[perm[c]];
        absl[c] = l.abs();
        if l < 0.0 { set(&mut hd, c); }
    }
    let dist = |cw: &Row| -> f32 {
        let mut d = 0f32;
        for w in 0..3 {
            let mut x = cw[w] ^ hd[w];
            while x != 0 {
                let b = x.trailing_zeros() as usize;
                d += absl[w * 64 + b];
                x &= x - 1;
            }
        }
        d
    };

    // Rzad 0: twarda decyzja na bazie informacyjnej, przekodowana.
    let mut c0: Row = [0; 3];
    for kk in 0..91 {
        if get(&hd, pivot_col[kk]) {
            for w in 0..3 { c0[w] ^= rows[kk][w]; }
        }
    }
    let mut best = c0;
    let mut best_d = dist(&c0);
    // Rzad 1.
    for kk in 0..91 {
        let mut c: Row = c0;
        for w in 0..3 { c[w] ^= rows[kk][w]; }
        let d = dist(&c);
        if d < best_d { best_d = d; best = c; }
    }
    // Rzad 2 na najmniej pewnych bitach bazy (pivoty sa w kolejnosci malejacej pewnosci).
    let lo = 91 - order2_width.min(91);
    for a in lo..91 {
        let mut ca: Row = c0;
        for w in 0..3 { ca[w] ^= rows[a][w]; }
        for b in (a + 1)..91 {
            let mut c: Row = ca;
            for w in 0..3 { c[w] ^= rows[b][w]; }
            let d = dist(&c);
            if d < best_d { best_d = d; best = c; }
        }
    }

    let mut cw = [0u8; 174];
    for c in 0..174 {
        if get(&best, c) { cw[perm[c]] = 1; }
    }
    let mut b91 = [0u8; 91];
    b91.copy_from_slice(&cw[..91]);
    if !check_crc(&b91) { return None; }
    Some((cw, best_d))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::decode::params::NM;

    // Independent parity check (straight from params::NM, a different
    // encoding of the same code than GEN_PARITY) - used to verify
    // GEN_PARITY's port from ft8_encoder.py, not to duplicate ldpc::parity_check.
    fn parity_via_nm(bits174: &[u8; 174]) -> bool {
        for row in NM.iter() {
            let mut x = 0u8;
            for &idx in row.iter() {
                if idx == 0 { break; }
                x ^= bits174[(idx as usize) - 1];
            }
            if x != 0 { return false; }
        }
        true
    }

    #[test]
    fn gen_parity_matches_nm_parity_check() {
        // Deterministic pseudo-random 91-bit words (no external RNG crate
        // in this codebase) - encode via GEN_PARITY, verify against the
        // INDEPENDENT NM-based parity check. A transcription error in
        // GEN_PARITY would fail this even though NM lives in a completely
        // separate file/format.
        let mut seed: u64 = 12345;
        for _trial in 0..20 {
            let mut bits91 = [0u8; 91];
            for b in bits91.iter_mut() {
                seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1);
                *b = ((seed >> 33) & 1) as u8;
            }
            let cw = ldpc_encode_systematic(&bits91);
            assert!(parity_via_nm(&cw), "GEN_PARITY produced a codeword failing the independent NM parity check");
        }
    }

    #[test]
    fn osd_full_recovers_codeword_with_confident_wrong_bits() {
        // Build a 91-bit message+CRC word with a VALID CRC-14 - check_crc
        // is the real acceptance gate for OSD (see the module doc comment:
        // LDPC parity alone is trivially satisfied by ANY systematic word
        // under this encoding, so it can't distinguish a correct guess
        // from a wrong one - only CRC-14, embedded in these same 91 bits,
        // can).
        let mut bits91 = [0u8; 91];
        for (i, b) in bits91.iter_mut().take(77).enumerate() { *b = ((i * 7 + 3) % 2) as u8; }
        let mut padded = [0u8; 82];
        padded[..77].copy_from_slice(&bits91[..77]);
        let crc = crc14(&padded);
        for i in 0..14 {
            bits91[77 + i] = ((crc >> (13 - i)) & 1) as u8;
        }
        assert!(check_crc(&bits91), "test setup: constructed CRC must be valid");

        let good_cw = ldpc_encode_systematic(&bits91);
        assert!(parity_via_nm(&good_cw), "test setup: good_cw must itself be a valid codeword");

        // Strong, EQUAL-magnitude correct-sign LLR for every bit, except
        // one systematic bit whose SIGN is flipped (magnitude unchanged) -
        // simulates BP converging to the wrong hard decision on that one
        // bit while treating it as no less reliable than any other (worst
        // case for reliability-ordering: ties resolve in index order, so
        // this only proves recovery, not that ordering itself helps -
        // that's fine, ordering is a heuristic for trying fewer candidates
        // first, not a correctness requirement).
        // Slabe, ale poprawne LLR wszedzie poza kilkoma bitami o PEWNYM,
        // blednym znaku (tak, ze sama twarda decyzja daje zle slowo). Pelny
        // OSD musi wrocic do poprawnego slowa kodowego (z poprawnym CRC).
        let mut llr = [0f32; 174];
        for i in 0..174 {
            let m = 1.0 + (i % 7) as f32;
            llr[i] = if good_cw[i] == 0 { m } else { -m };
        }
        for &i in &[3usize, 120, 150] { llr[i] = -llr[i] * 0.2; }
        let (cw, _d) = osd_full(&llr, 40).expect("osd_full musi odzyskac slowo");
        assert_eq!(cw, good_cw);
    }

    #[test]
    fn osd_full_rejects_word_failing_crc() {
        // Slowo kodowe z ZLYM CRC (dane bez poprawnej sumy) - OSD znajdzie je
        // jako najblizsze, ale CRC musi je odrzucic.
        let mut bits91 = [0u8; 91];
        bits91[5] = 1;
        let cw = ldpc_encode_systematic(&bits91);
        assert!(!check_crc(&bits91));
        let mut llr = [0f32; 174];
        for i in 0..174 { llr[i] = if cw[i] == 0 { 4.0 } else { -4.0 }; }
        assert!(osd_full(&llr, 40).is_none());
    }
}
